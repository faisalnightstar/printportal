                    <div class="w-2 h-2 bg-gray-400 rounded-full animate-bounce" style="animation-delay: 300ms"></div>
                </div>
            `;
        chatMessages.appendChild(msgDiv);
        scrollToBottom();
    }

    function removeTypingIndicator() {
        const indicator = document.getElementById('typing-indicator');
        if (indicator) {
            indicator.remove();
        }
    }

    async function sendMessage() {
        const text = chatInput.value.trim();
        if (!text) return;

        // Update UI
        addMessageToUI('user', text);
        chatInput.value = '';
        showTypingIndicator();

        // Prepare history for API
        const contents = chatHistory.map(msg => ({
            role: msg.role === 'bot' ? 'model' : 'user',
            parts: [{
                text: msg.text
            }]
        }));
        contents.push({
            role: 'user',
            parts: [{
                text: text
            }]
        });

        const apiKey = ""; // Canvas handles API key injection
        const apiUrl =
            `https://generativelanguage.googleapis.com/v1beta/models/gemini-3-flash-preview:generateContent?key=${apiKey}`;

        const payload = {
            contents: contents,
            systemInstruction: {
                parts: [{
                    text: systemInstruction
                }]
            }
        };

        try {
            // Implement exponential backoff for robustness
            let response;
            let retries = 3;
            let delay = 1000;

            while (retries > 0) {
                response = await fetch(apiUrl, {
                    method: 'POST',
                    headers: {
                        'Content-Type': 'application/json'
                    },
                    body: JSON.stringify(payload)
                });

                if (response.ok) break;
                if (response.status === 429) {
                    retries--;
                    await new Promise(res => setTimeout(res, delay));
                    delay *= 2;
                } else {
                    throw new Error(`HTTP error! status: ${response.status}`);
                }
            }

            if (!response || !response.ok) throw new Error("Failed to fetch after retries");

            const data = await response.json();
            const botReply = data.candidates?. [0]?.content?.parts?. [0]?.text;

            if (botReply) {
                removeTypingIndicator();
                addMessageToUI('bot', botReply);

                // Save to history
                chatHistory.push({
                    role: 'user',
                    text: text
                });
                chatHistory.push({
                    role: 'bot',
                    text: botReply
                });
            } else {
                throw new Error("Unexpected API response structure");
            }

        } catch (error) {
            console.error("Gemini API Error:", error);
            removeTypingIndicator();
            addMessageToUI('bot',
                "I'm having trouble connecting to my servers right now. Please try again in a moment.");
        }
    }
